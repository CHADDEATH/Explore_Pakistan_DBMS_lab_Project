-- Table: CITIES
-- Central reference table for major destinations across Pakistan.
CREATE TABLE cities (
    city_id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city_name       VARCHAR2(50) NOT NULL UNIQUE,
    province        VARCHAR2(50) NOT NULL,
    region_type     VARCHAR2(30) NOT NULL,
    description     VARCHAR2(1000),
    source_url      VARCHAR2(500),
    date_retrieved  DATE DEFAULT SYSDATE
);

-- Table: HOTELS
-- Accommodations in each city with star rating (2 to 5) and Oracle 23ai VECTOR column.
CREATE TABLE hotels (
    hotel_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city_id         NUMBER NOT NULL,
    hotel_name      VARCHAR2(150) NOT NULL,
    star_rating     NUMBER(1) NOT NULL,
    address         VARCHAR2(255) NOT NULL,
    contact         VARCHAR2(100),
    rating_avg      NUMBER(3,2) DEFAULT 0.0,
    embedding       VECTOR(384, FLOAT32), -- Oracle 23ai Vector embedding for AI search
    source_url      VARCHAR2(500),
    date_retrieved  DATE DEFAULT SYSDATE
);

-- Table: ROOM_TYPES
-- Specific room tiers offered by hotels with night rates in PKR and capacity.
CREATE TABLE room_types (
    room_id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hotel_id        NUMBER NOT NULL,
    room_name       VARCHAR2(100) NOT NULL,
    capacity        NUMBER(2) NOT NULL,
    price_per_night NUMBER(10,2) NOT NULL,
    amenities       VARCHAR2(255),
    source_url      VARCHAR2(500),
    date_retrieved  DATE DEFAULT SYSDATE
);

-- Table: LANDMARKS
-- Cultural, historical, natural, and religious attractions with entry fees.
CREATE TABLE landmarks (
    landmark_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city_id         NUMBER NOT NULL,
    landmark_name   VARCHAR2(150) NOT NULL,
    category        VARCHAR2(50) NOT NULL,
    entry_fee       NUMBER(8,2) DEFAULT 0.00 NOT NULL,
    description     VARCHAR2(1000),
    embedding       VECTOR(384, FLOAT32), -- Oracle 23ai Vector embedding for semantic queries
    source_url      VARCHAR2(500),
    date_retrieved  DATE DEFAULT SYSDATE
);

-- Table: STREET_FOODS
-- Iconic culinary items and street delicacies with famous spots and price ranges.
CREATE TABLE street_foods (
    food_id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city_id         NUMBER NOT NULL,
    food_name       VARCHAR2(150) NOT NULL,
    category        VARCHAR2(50),
    famous_spot     VARCHAR2(150),
    price_range     VARCHAR2(50),
    is_street_food  CHAR(1) DEFAULT 'Y' NOT NULL,
    description     VARCHAR2(1000),
    source_url      VARCHAR2(500),
    date_retrieved  DATE DEFAULT SYSDATE
);

-- Table: TRANSPORT_ROUTES
-- Public transit and shared shuttle corridors connecting hubs/hotels to landmarks.
CREATE TABLE transport_routes (
    route_id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city_id          NUMBER NOT NULL,
    from_location    VARCHAR2(150) NOT NULL,
    to_landmark_id   NUMBER NOT NULL,
    transport_mode   VARCHAR2(50) NOT NULL,
    is_public        CHAR(1) DEFAULT 'Y' NOT NULL,
    fare             NUMBER(8,2) NOT NULL,
    duration_minutes NUMBER(4) NOT NULL,
    source_url       VARCHAR2(500),
    date_retrieved   DATE DEFAULT SYSDATE
);

-- Table: PRIVATE_TRANSPORT
-- Ride-hailing apps (Careem, InDrive, Yango) and chauffeur/4x4 rental tariffs.
CREATE TABLE private_transport (
    ride_id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city_id         NUMBER NOT NULL,
    app_name        VARCHAR2(50) NOT NULL,
    vehicle_type    VARCHAR2(50) NOT NULL,
    base_fare       NUMBER(8,2) NOT NULL,
    per_km_rate     NUMBER(8,2) NOT NULL,
    source_url      VARCHAR2(500),
    date_retrieved  DATE DEFAULT SYSDATE
);

-- Table: TOUR_GUIDES
-- Certified local travel guides with language capabilities and daily PKR rates.
CREATE TABLE tour_guides (
    guide_id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city_id          NUMBER NOT NULL,
    guide_name       VARCHAR2(100) NOT NULL,
    languages        VARCHAR2(150) NOT NULL,
    daily_rate       NUMBER(10,2) NOT NULL,
    contact          VARCHAR2(50),
    experience_years NUMBER(2) DEFAULT 1,
    source_url       VARCHAR2(500),
    date_retrieved   DATE DEFAULT SYSDATE
);

-- Table: ACTIVITIES
-- Tours and excursion activities available in each destination.
CREATE TABLE activities (
    activity_id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city_id                  NUMBER NOT NULL,
    activity_name            VARCHAR2(150) NOT NULL,
    activity_type            VARCHAR2(50),
    estimated_duration_hours NUMBER(3,1),
    description              VARCHAR2(1000),
    source_url               VARCHAR2(500),
    date_retrieved           DATE DEFAULT SYSDATE
);

-- Table: GUIDE_ACTIVITIES (Junction Table M:N)
-- Resolves the many-to-many relationship between certified guides and offered activities.
CREATE TABLE guide_activities (
    guide_id    NUMBER NOT NULL,
    activity_id NUMBER NOT NULL,
    PRIMARY KEY (guide_id, activity_id)
);

-- Table: REVIEWS
-- Feedback and star ratings for hotels, street foods, or landmarks.
-- Uses multi-column foreign keys with an exclusivity check constraint to ensure 100% 3NF referential integrity.
CREATE TABLE reviews (
    review_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hotel_id       NUMBER,
    food_id        NUMBER,
    landmark_id    NUMBER,
    reviewer_name  VARCHAR2(100) NOT NULL,
    rating         NUMBER(1) NOT NULL,
    review_text    VARCHAR2(1000),
    review_date    DATE DEFAULT SYSDATE NOT NULL
);

-- Table: BOOKINGS
-- Reservations for hotel rooms with guest details, stay dates, and calculated price.
CREATE TABLE bookings (
    booking_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hotel_id       NUMBER NOT NULL,
    room_id        NUMBER NOT NULL,
    guest_name     VARCHAR2(100) NOT NULL,
    guest_contact  VARCHAR2(50) NOT NULL,
    check_in_date  DATE NOT NULL,
    check_out_date DATE NOT NULL,
    total_price    NUMBER(12,2) NOT NULL,
    status         VARCHAR2(20) DEFAULT 'CONFIRMED' NOT NULL,
    created_at     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

-- Table: SEASONS
-- Recommended travel seasons, weather patterns, and tourist suitability scores.
CREATE TABLE seasons (
    season_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city_id          NUMBER NOT NULL,
    season_name      VARCHAR2(50) NOT NULL,
    ideal_months     VARCHAR2(100) NOT NULL,
    avg_temp_celsius VARCHAR2(30),
    weather_notes    VARCHAR2(500) NOT NULL,
    visit_rating     NUMBER(2,1) NOT NULL,
    source_url       VARCHAR2(500),
    date_retrieved   DATE DEFAULT SYSDATE
);

-- Table: EMERGENCY_CONTACTS
-- Essential helplines, tourist police, hospitals, and disaster management contacts.
CREATE TABLE emergency_contacts (
    contact_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city_id          NUMBER NOT NULL,
    service_type     VARCHAR2(50) NOT NULL,
    institution_name VARCHAR2(150) NOT NULL,
    phone_number     VARCHAR2(50) NOT NULL,
    address          VARCHAR2(255),
    source_url       VARCHAR2(500),
    date_retrieved   DATE DEFAULT SYSDATE
);

-- Table: CURRENCIES
-- Currency conversion rates against PKR (e.g. USD, EUR, GBP, AED, SAR).
CREATE TABLE currencies (
    currency_code        VARCHAR2(3) PRIMARY KEY,
    currency_name        VARCHAR2(50) NOT NULL,
    exchange_rate_to_pkr NUMBER(12,4) NOT NULL,
    last_updated         DATE DEFAULT SYSDATE NOT NULL,
    source_url           VARCHAR2(500)
);

-- Table: USERS_ADMIN
-- Administrator credentials. Passwords are NOT stored in plain text; salted SHA-256 hash is enforced.
CREATE TABLE users_admin (
    admin_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR2(50) NOT NULL UNIQUE,
    password_hash VARCHAR2(128) NOT NULL,
    salt          VARCHAR2(64) NOT NULL,
    created_at    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

-- Table: AUDIT_LOG
-- Records every administrative INSERT, UPDATE, and DELETE for compliance tracking.
CREATE TABLE audit_log (
    log_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_name    VARCHAR2(50) NOT NULL,
    operation     VARCHAR2(10) NOT NULL,
    record_id     VARCHAR2(100),
    old_values    CLOB,
    new_values    CLOB,
    admin_user    VARCHAR2(100) DEFAULT USER NOT NULL,
    log_timestamp TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

